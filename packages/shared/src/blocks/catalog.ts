function modelEnum(models: ModelOption[], slugs?: string[]) {
  const list = slugs ? models.filter((model) => slugs.includes(model.slug)) : models;
  return {
    enum: list.map((model) => model.slug),
    enumLabels: Object.fromEntries(list.map((model) => [model.slug, model.title])),
  };
}

